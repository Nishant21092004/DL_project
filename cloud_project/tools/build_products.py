def reviews_for(slug, rating):
    """Deterministic pseudo-random review count."""
    h = sum(ord(c) for c in slug)
    base = 40 + (h * 37) % 460
    return base + int(rating * 10)


def main():
    products = []
    for i, (slug, name, cat, price, mrp, rating, badge, desc, tags) in enumerate(SPEC, 1):
        folder = os.path.join(ASSETS, slug)
        imgs = []
        if os.path.isdir(folder):
            imgs = [f"{n}" for n in range(1, 5)
                    if os.path.exists(os.path.join(folder, f"{n}.jpg"))]
        if not imgs:
            raise SystemExit(f"NO IMAGES for {slug}")
        products.append({
            "id": i,
            "slug": slug,
            "name": name,
            "category": cat,
            "price": price,
            "mrp": mrp,
            "rating": rating,
            "reviews": reviews_for(slug, rating),
            "badge": badge,
            "desc": desc,
            "tags": tags,
            "images": [f"assets/products/{slug}/{n}.jpg" for n in imgs],
        })
    counts = {}
    for p in products:
        counts[p["category"]] = counts.get(p["category"], 0) + 1
    js = ("// Auto-generated by tools/build_products.py - do not edit by hand\n"
          "// Total products: %d\n" % len(products))
    js += "const PRODUCTS = " + json.dumps(products, ensure_ascii=False, indent=1) + ";\n"
    out = os.path.join(ROOT, "js", "products.js")
    with open(out, "w") as f:
        f.write(js)
    print(f"Wrote {out}: {len(products)} products {counts}")


if __name__ == "__main__":
    main()
